// Helper to get unique departments
export const getUniqueDepartments = (): string[] => {
  return [...new Set(mockSelectableUsers.map(u => u.department))].sort();
};

// Helper to get unique roles
export const getUniqueRoles = (): string[] => {
  return [...new Set(mockSelectableUsers.map(u => u.role))].sort();
};

// Filter users based on tile eligibility rules
export const filterEligibleUsers = (
  users: SelectableUser[],
  allowedRoles: string[],
  allowedDepartments: string[],
  activeOnly: boolean = true
): SelectableUser[] => {
  return users.filter(user => {
    // Filter inactive if activeOnly
    if (activeOnly && user.status !== 'active') {
      return false;
    }
    
    // If no role restrictions, all roles are allowed
    const roleAllowed = allowedRoles.length === 0 || allowedRoles.includes(user.role);
    
    // If no department restrictions, all departments are allowed
    const deptAllowed = allowedDepartments.length === 0 || allowedDepartments.includes(user.department);
    
    return roleAllowed && deptAllowed;
  });
};
